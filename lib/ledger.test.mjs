import assert from "node:assert/strict";
import { emptyState, recordEntry, undoEntry, balances, toCents, setBalances, applyMemoryCommand } from "./ledger.ts";

const state = emptyState();
state.accounts[0].initial = 10000;
state.accounts[1].initial = 5000;
const make = (kind, amount) => ({
  kind, amount, account: "现金", category: "餐饮", note: "synthetic test", date: "2026-09-17",
});
assert.equal(toCents("0.29"), 29);
for (const value of ["-1", "NaN", "1.001", "1e3", ""]) assert.throws(() => toCents(value));
recordEntry(state, make("expense", "20"), "one");
assert.equal(balances(state)["现金"], 8000);
assert.throws(() => recordEntry(state, make("expense", "20"), "one"));
recordEntry(state, make("income", "10"), "two");
assert.equal(balances(state)["现金"], 9000);
recordEntry(state, { ...make("transfer", "30"), target: "银行卡" }, "three");
assert.deepEqual([balances(state)["现金"], balances(state)["银行卡"]], [6000, 8000]);
assert.throws(() => recordEntry(state, make("expense", "61"), "bad"));
assert.throws(() => recordEntry(state, { ...make("expense", "1"), date: "2026-02-30" }, "date"));
assert.throws(() => recordEntry(state, { ...make("expense", "1"), account: "余额宝" }, "unknown"));
undoEntry(state, "three");
undoEntry(state, "three");
assert.deepEqual([balances(state)["现金"], balances(state)["银行卡"]], [9000, 5000]);
undoEntry(state, "one");
assert.equal(balances(state)["现金"], 11000);
recordEntry(state, make("expense", "110"), "four");
assert.throws(() => undoEntry(state, "two"));
assert.equal(balances(state)["现金"], 0);
assert.equal(balances(JSON.parse(JSON.stringify(state)))["现金"], 0);
console.log("PASS: cents, income, expense, transfer, duplicate prevention, undo, invalid inputs and serialization");
const editable = emptyState();
setBalances(editable, { "现金": "100", "银行卡": "" });
recordEntry(editable, make("expense", "20"), "expense");
setBalances(editable, { "现金": "50" });
assert.equal(balances(editable)["现金"], 5000);
assert.equal(editable.entries.length, 1);
assert.equal(editable.entries[0].cents, 2000);
setBalances(editable, { "现金": "50" });
assert.equal(balances(editable)["现金"], 5000);
undoEntry(editable, "expense");
assert.equal(balances(editable)["现金"], 7000);
const beforeInvalid = JSON.stringify(editable);
assert.throws(() => setBalances(editable, { "现金": "10", "银行卡": "-1" }));
assert.equal(JSON.stringify(editable), beforeInvalid);
assert.throws(() => setBalances(editable, { "不存在": "1" }));
assert.throws(() => setBalances(editable, { "现金": "" }));
setBalances(editable, { "现金": "0" });
assert.equal(balances(JSON.parse(JSON.stringify(editable)))["现金"], 0);
assert.equal(balances(editable)["银行卡"], null);
console.log("PASS: editable balances, retained entries, repeated updates, undo, atomic validation and zero balance");
const memoryState = emptyState();
const first = "00000000-0000-4000-8000-000000000001";
const second = "00000000-0000-4000-8000-000000000002";
assert.match(applyMemoryCommand(memoryState, { action: "remember", fact: "我更喜欢简短直接的回答" }, first), /记住了/);
assert.equal(memoryState.memories.length, 1);
assert.match(applyMemoryCommand(memoryState, { action: "remember", fact: "我更喜欢简短直接的回答" }, second), /已经记得/);
assert.equal(memoryState.memories.length, 1);
assert.match(applyMemoryCommand(memoryState, { action: "list" }, second), /简短直接/);
assert.match(applyMemoryCommand(memoryState, { action: "update", id: first, fact: "技术问题可以详细解释" }, second), /改好了/);
assert.equal(memoryState.memories[0].fact, "技术问题可以详细解释");
assert.match(applyMemoryCommand(memoryState, { action: "forget", id: first }, second), /忘掉了/);
assert.equal(memoryState.memories.length, 0);
assert.throws(() => applyMemoryCommand(memoryState, { action: "forget", id: first }, second));
const full = emptyState();
for (let i = 0; i < 100; i++) full.memories.push({ id: crypto.randomUUID(), fact: "记忆" + i, createdAt: "", updatedAt: "" });
assert.throws(() => applyMemoryCommand(full, { action: "remember", fact: "超出上限" }, first));
console.log("PASS: long-term memory remember, deduplicate, list, update, forget and limit");
