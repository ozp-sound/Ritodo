import assert from "node:assert/strict";
import { teachingWeek, coursesOn, timetableContext, answerCourseQuestion } from "./timetable.ts";

const at = value => timetableContext(new Date(value + "+08:00"));
assert.equal(teachingWeek("2026-09-24"), 3);
assert.equal(teachingWeek("2026-09-27"), 3);
assert.equal(teachingWeek("2026-09-28"), 4);
assert.equal(coursesOn("2026-09-21")[0].name, "高等数学");
assert.equal(coursesOn("2026-09-23")[0].name, "计算机基础");
assert.equal(at("2026-09-21T08:00:00").current.name, "高等数学");
assert.equal(at("2026-09-21T09:30:00").current, null);
assert.equal(at("2026-09-21T09:40:00").next.name, "计算机基础");
assert.equal(at("2026-09-27T23:59:59").week, 3);
assert.equal(at("2026-09-28T00:00:00").week, 4);
assert.equal(at("2026-12-28T08:00:00").inSemester, false);
assert.equal(at("2026-12-28T08:00:00").next, null);
assert.match(answerCourseQuestion("明天有什么课？", new Date("2026-09-22T10:00:00+08:00")), /实验楼 201/);
assert.match(answerCourseQuestion("下一节什么课，在哪上？", new Date("2026-09-22T11:30:00+08:00")), /计算机基础/);
assert.equal(answerCourseQuestion("明天有什么课，另外午饭花了20元"), null);
assert.equal(answerCourseQuestion("现金午饭20元"), null);
console.log("PASS: configurable semester weeks, courses, breaks, semester end and chat intent");
